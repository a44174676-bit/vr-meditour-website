const navToggle = document.querySelector('.nav-toggle');
const navLinks = document.querySelectorAll('.nav-menu a');
const year = document.querySelector('#year');
const languageButtons = document.querySelectorAll('.lang-btn');
const metaDescription = document.querySelector('meta[name="description"]');
const defaultLanguage = 'zh';

if (year) {
  year.textContent = new Date().getFullYear();
}

function applyLanguage(language) {
  const selected = translations[language] ? language : defaultLanguage;
  const dictionary = translations[selected];

  document.documentElement.lang = selected === 'zh' ? 'zh-CN' : selected;
  document.title = dictionary.pageTitle;

  if (metaDescription) {
    metaDescription.setAttribute('content', dictionary.metaDescription);
  }

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === selected;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  localStorage.setItem('hnkLanguage', selected);
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => applyLanguage(button.dataset.lang));
});

if (navToggle) {
  navToggle.addEventListener('click', () => {
    const isOpen = document.body.classList.toggle('nav-open');
    navToggle.setAttribute('aria-expanded', String(isOpen));
  });
}

navLinks.forEach((link) => {
  link.addEventListener('click', () => {
    document.body.classList.remove('nav-open');
    navToggle?.setAttribute('aria-expanded', 'false');
  });
});

document.querySelectorAll('.media-placeholder[data-image]').forEach((element) => {
  const imageUrl = element.getAttribute('data-image');
  if (!imageUrl) return;

  const image = new Image();
  image.onload = () => {
    element.style.backgroundImage = `linear-gradient(135deg, rgba(5, 7, 13, 0.46), rgba(5, 7, 13, 0.78)), url('${imageUrl}')`;
    element.classList.add('has-image');
  };
  image.src = imageUrl;
});

const revealElements = document.querySelectorAll('.reveal');

if ('IntersectionObserver' in window) {
  const revealObserver = new IntersectionObserver((entries, observer) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add('is-visible'));
}

