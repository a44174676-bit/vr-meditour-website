export function translateUI(languageCode, key, values = {}) {
  const dictionary = UI_TRANSLATIONS[languageCode] || UI_TRANSLATIONS.ko;
  const template = dictionary[key] ?? UI_TRANSLATIONS.ko[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function normalizeUILanguage(value, supportedCodes = Object.keys(UI_TRANSLATIONS)) {
  const code = String(value || "").toLowerCase().split("-")[0];
  return supportedCodes.includes(code) ? code : null;
}

export function resolveUILanguage({ query, stored, browser, supportedCodes = Object.keys(UI_TRANSLATIONS) }) {
  return normalizeUILanguage(query, supportedCodes)
    || normalizeUILanguage(stored, supportedCodes)
    || normalizeUILanguage(browser, supportedCodes)
    || "ko";
}
